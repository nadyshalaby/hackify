# THE PHASE 5 REVIEWER RENAME, PINNED FROM BOTH ENDS, on the shape
# 73-implementer-rename.sh built for check [40] and for the same reason. That
# block's header records the incident: commit dabc333 renamed the implementer
# agent, left every dispatch site naming a type that no longer existed, and the
# tree stayed fully green through a tagged release, because an agent type is
# resolved by the harness at DISPATCH time, long after the validator has had its
# say. Nothing in this repo greps an agent-type string on its own.
#
# WHICH RENAME IS POLICED HERE. 0.18.0 made the merged all-lens reviewer the
# default route in every mode, which retired the word "merged": it only ever
# meant something while there was a panel to merge FROM. So all six reviewer
# agents became one family and every one of them moved:
#
#     code-reviewer-merged        -> reviewer
#     code-reviewer-security      -> reviewer-security
#     code-reviewer-quality-plan  -> reviewer-quality-plan
#     code-reviewer-performance   -> reviewer-performance
#     code-reviewer-coherence     -> reviewer-coherence
#     design-conformance-reviewer -> reviewer-design
#
# `finding-refuter` is not a reviewer and did not move; neither did any other
# agent. The agents/*.md filenames moved with the types.
#
# WHY THIS IS A SEPARATE BLOCK FROM [40] RATHER THAN SIX MORE LITERALS IN IT.
# [40]'s scope excludes docs/work/* and CHANGELOG.md wholesale and its own
# fragment path, and every one of those rows is argued there for the IMPLEMENTER
# rename specifically. Feeding six unrelated literals through that block would
# inherit an exclusion set nobody re-argued and would leave one hand-written size
# bound policing two renames that move on different schedules. The seam is
# responsibility, the same seam 71's and 73's headers argue for.
#
# WHAT THIS BLOCK IS NOT. [30] in 60-primitives.sh counts agents/ against a list
# and matches each file's frontmatter `name:`; [87] reads the dispatch roster in
# parallel-agents/README.md from both ends against agents/. Both are roster
# checks and both discover their own sets, so both moved with this rename for
# free and neither noticed it happened. That is exactly the gap here: a rename is
# invisible to a check that reads the tree's CURRENT shape, because the current
# shape is self-consistent whether or not the rename finished. Only a scan for
# the DEAD name can tell a finished rename from a half-finished one.
#
# ---------------------------------------------------------------------------
# THE ABSENT HALF IS THE LOAD-BEARING ONE, and it is why the scan roots are wide.
# A rename across twenty-seven files is exactly where one quiet survivor hides in
# a file nobody thought to open, and a check that reads only the files the rename
# touched cannot catch what the rename missed. So the scan reads the whole tree
# under the pathspec below, not a hand-written site list.
#
# THE EXCLUDED PATHS ARE THE ONES ALLOWED TO SAY THE OLD WORDS, and each row is
# a claim about what is really in it rather than a glob thrown at a red.
#
#   dist/*          generated by scripts/sync-runtimes.sh from the canonical
#                   trees this block already scans, so a hit there is a stale
#                   build and check [56] is the instrument that says so.
#   docs/work/*     the sprint record. An archived work-doc under docs/work/done/
#                   quotes the tree as it stood, and rewriting one to green a
#                   check would be falsifying the record the check exists to
#                   protect. THE LIVE DOC IS THE SAME CLASS AND THE ROW COVERS IT
#                   DELIBERATELY: a work-doc that carries out a rename cannot
#                   describe its own task without naming what it renamed, so a
#                   narrower row stopping at done/ would force the next rename's
#                   author to reword their own backlog to keep this green. That
#                   is the same falsification one directory up. [98] and [99]
#                   already police work-doc content from their own angles.
#   CHANGELOG.md    release history, which has to be able to name what was
#                   renamed. THIS ROW WAIVES REAL OCCURRENCES, measured rather
#                   than assumed: 9 survive in shipped entries at the time of
#                   writing, from 0.13.0's reviewer merge down to 0.9.x, and
#                   every one of them is a sentence that cannot be written
#                   without the old name. It also waives the UNRELEASED entry at
#                   the top, which is a real cost and is stated rather than
#                   hidden; the same cost [40]'s CHANGELOG row carries and
#                   records.
#   this fragment   it holds the very literals it bans. [40]'s self-exclusion
#                   travelled with it through two file splits and its header
#                   warns whoever moves it next; the same warning applies to the
#                   path below. A [89] that moved house while that path stayed
#                   behind would red on its own text in the middle of the move.
#
# ':(top)' IS THE POSITIVE HALF AND IT IS NOT DECORATION, for the reason [40]
# states: a pathspec list made of nothing but exclusions is one reading away from
# resolving to no files at all, and a scan over no files prints green forever.
# 'top' also anchors every entry to the repo root rather than to the caller's
# working directory.
#
# ---------------------------------------------------------------------------
# THE SCAN READS UNTRACKED FILES TOO, WHICH IS WHERE THIS DIVERGES FROM [40], and
# the divergence is measured rather than stylistic. [40] scans tracked paths and
# argues untracked ones buy no coverage because [55] already reds on an
# uncommitted file under skills/, agents/ and hooks/. That argument has a hole
# this rename walked straight into: [55] does not cover scripts/, and the sprint
# that shipped this block had SEVEN untracked files under scripts/ at the moment
# the rename ran. A tracked-only scan would have greened over a dead name in any
# of them. `--untracked` closes that at the price of one flag, and it honours
# .gitignore, so build output and local scratch stay out of the scan the same way
# they stay out of [55]'s discovery.
#
# AND IT DOES NOT READ THE INDEX, WHICH IS THE OTHER DIVERGENCE. [40] unions a
# --cached scan onto its worktree scan to catch a mid-rename `rm <file>` that was
# never staged. That half is wrong for THIS check, and the number is what settles
# it: run over this repository at the commit that finished the rename, the
# --cached scan returned 10 files, and all 10 were files whose WORKTREE copy was
# already correct and whose index still held the pre-rename blob because the wave
# had not been committed yet. A rename lives its whole life in that pre-commit
# window, so a --cached half would make this block red for the entire time it is
# the only thing watching, and the only way to green it would be to stop trusting
# it. In CI the index and the worktree are identical, so that half would change
# no verdict there either. What it would have caught instead is covered twice
# over: the old agents/ paths are asserted ABSENT FROM DISK below, [30] counts
# agents/ against its own roster, and [55] reds on an uncommitted file under
# agents/.

yellow "[89] the Phase 5 reviewer rename, live names present and dead names absent"

# ---------------------------------------------------------------------------
# PRESENT, PART ONE: THE DISPATCH SITES.
#
# Every file that tells a dispatcher which type to send, or teaches the dispatch
# in prose a reader follows. A rename that reached the roster while missing the
# prose leaves a reader dispatching a type that no longer resolves, which is the
# 0.15.0 incident [40] was built for.
#
# THE TOKEN CARRIES ITS CLOSING BACKTICK ON PURPOSE. Bare 'hackify:reviewer' is a
# PREFIX of all five lens types, so a file naming only `hackify:reviewer-security`
# would satisfy a bare pin while saying nothing about the default reviewer. The
# backticked form is the exact one every site below writes, and it is the only
# form that distinguishes the merged type from its five siblings.
#
# The size is hand-written beside the list, the shape [40], [77] and [80] all use:
# a bound read back out of the list it polices cannot police that list. Drop a
# site and the element count drops with it, so that site's own check leaves the
# run and the run stays green one check shorter.
# EVERY RED THIS BLOCK PRINTS NAMES [89], the presence reds included, which is
# why the two loops below call a local matcher instead of the shared presence
# helper in 00-helpers.sh. That helper's red is worded for a reader looking at
# the transcript with the yellow header still in view; this bar prints roughly
# 1900 lines, and the first thing anyone does with a red is grep for it, at which
# point a message carrying no check id has to be routed by counting backwards to
# the nearest header. The absent half below already names itself on every branch,
# so the block would otherwise be half attributable. The test is the same
# one-line fixed-string match against a FILE, never a pipe, which is what keeps
# it clear of check [84]; only the wording differs, and the ok line names the
# check for the same reason the red does.
rrn_present() {
  local token="$1" path="$2"
  if grep -qF -- "$token" "$path" 2>/dev/null; then
    green "  ok   [89] '$token' present in $path"
  else
    red "  FAIL [89] '$token' is missing from $path, a site that dispatches or teaches the Phase 5 reviewer; the rename reached the roster and left this reader following a type that no longer resolves"
    FAILED=$((FAILED + 1))
  fi
}

