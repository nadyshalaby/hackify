# THE ORDER OF THESE TWO LISTS IS NOT ASSERTED and does not need to be:
# RRN_OLD_AGENTS above asks whether a FILE exists and RRN_DEAD asks whether a
# WORD survives, so they are the same six strings answering two questions. They
# are written twice rather than aliased because each carries its own hand-written
# bound, and one bound over two meanings is the shape [40]'s WI_BANNED comment
# warns against.

RRN_LIVE_PATHS=(':(top)' ':(top,exclude)dist/*' ':(top,exclude)docs/work/*')
RRN_LIVE_PATHS+=(':(top,exclude)CHANGELOG.md')
RRN_LIVE_PATHS+=(':(top,exclude)scripts/validate-dod.d/89-reviewer-rename.sh')

# STATUS IS GIT GREP'S ALONE, the contract [40]'s wi_absent states and the reason
# it states it: rc 0 is a hit, rc above 1 is a scan that never ran, and rc 1 DOES
# NOT settle the question by itself. git grep returns 1 both for a tree with no
# match and for a scan that could not stat a file it was asked to read. Measured
# there on git 2.50.1: one tracked file at mode 000 gives rc 1, empty stdout and a
# 'Permission denied' line on stderr, while the same file at mode 644 gives rc 1
# with stderr EMPTY. So stderr is the tie-breaker rc alone cannot be, and rc 1
# with anything on stderr is a scan that never ran and must never be the reason a
# dead name prints green.
#
# STDERR GOES TO ITS OWN FILE AND NEVER INTO `hits`. Merging it with `2>&1` would
# let a warning on an otherwise clean scan be read as a matched line, turning a
# clean tree into a phantom hit. `rc=$?` stays the very next statement after the
# substitution so nothing in between can overwrite the status the check rests on.
#
# THE mktemp IS CHECKED, and [40]'s header records what the unchecked version
# cost: a failed mktemp leaves the capture path empty, the redirection then dies
# in the shell BEFORE git runs, and bash hands back 1, which is a status git grep
# itself returns. With no capture file there is no stderr for the tie-breaker to
# read either, so the failure arrives wearing a clean tree's exact face and every
# call fails open at once.
#
# THE TEMP FILE IS TRAPPED AROUND ITS OWN WINDOW, not for the life of the
# fragment, and the clear is a RESTORE rather than a bare `trap - EXIT`. A sourced
# fragment shares one trap table with the whole run, so an EXIT trap left armed
# here would silently replace whatever the next fragment installs, and the tamper
# suite that drives this validator exits through a verdict trap a bare clear would
# delete.
# THE BODY IS rename_absent IN 00-helpers.sh, shared with [40] since the second
# use, and what is left here is the PROFILE. Every branch the paragraphs above
# argue is still what runs, and the canonical argument for each of them sits at the
# head of [40] in 73-implementer-rename.sh, which this was copied from.
#
# ONE MODE, AND IT IS THIS CHECK'S DECISION RATHER THAN A DEFAULT. `untracked`
# means `git grep --untracked`, the worktree plus the files .gitignore does not
# exclude, and no index scan at all. Both halves of that are measured directly
# above and neither survived into the shared body as a hard-coded choice: with one
# mode the verdicts print no mode word, because the word exists to say which half
# of a union spoke and there is no union here.
rrn_absent() {
  RN_ID='[89]'; RN_NOUN='retired reviewer name'; RN_LIST='ban list'
  RN_MODES=(untracked)
  RN_PATHS=(${RRN_LIVE_PATHS[@]+"${RRN_LIVE_PATHS[@]}"})
  rename_absent "$@"
}

# ONE SCAN FOR THE WHOLE BAN LIST, with the per-literal loop above kept as the
# fallback, which is the shape check_no_tokens_in uses in 00-helpers.sh and the
# one [40] adopted after measuring it. The batched grep answers ONLY the yes/no
# question "does anything in this list survive in this scope", and the moment the
# answer is anything but a clean no, the per-literal loop re-runs and words the
# verdict exactly as before. No diagnostic detail is traded for the speed: every
# red this block can print still names WHICH name survived and in WHICH file.
#
# THE SCREEN IS FAIL-CLOSED TOWARD THE SLOW PATH, never toward a green. Only rc 1
# with empty stderr is read as clean. A hit, a scan above rc 1, a scan that wrote
# to stderr, and an mktemp that produced no capture file all fall through to the
# loop, which reaches its own verdict with its own capture file. The screen can
# cost a repeat of the scan; it cannot be the reason a dead name prints green.
#
# -q RATHER THAN -n, since the screen discards output either way, and [40]
# measured that the stderr tie-breaker survives the quiet flag: a sealed tracked
# file returns rc 1 with the same stat error on stderr under -qF as under -nF.
#
# AN EMPTY LIST REFUSES rather than printing nothing, because a screen handed no
# patterns bans nothing while reporting a clean scan.
rrn_absent_all() {
  RN_ID='[89]'; RN_NOUN='retired reviewer name'; RN_LIST='ban list'
  RN_MODES=(untracked)
  RN_PATHS=(${RRN_LIVE_PATHS[@]+"${RRN_LIVE_PATHS[@]}"})
  rename_absent_all "$@"
}

# ---------------------------------------------------------------------------
# THE POSITIVE CONTROL, AND IT IS WHAT MAKES EVERY GREEN ABOVE WORTH READING.
# Everything the absent half prints on a clean tree is a zero, and a zero is
# worth exactly what the scan's ability to have returned non-zero is worth. This
# block shipped without one while [86], [87] and [88] each carried three, and a
# reviewer had to prove by hand, in a throwaway clone, that it could red at all.
# A proof that lives in somebody's transcript is not a proof the next run makes,
# so it is planted here and re-taken on every run.
#
# THE PLANT IS AN UNTRACKED FILE, WHICH IS THE HALF WORTH PROVING. `--untracked`
# is this check's one mode and the whole argument for the block above, so a
# control that could be satisfied by a tracked file would leave exactly the flag
# this fragment exists to justify unproven. Measured before the control was
# written: `git grep --untracked -F -e <literal>` over this scope finds the plant
# at rc 0, and the same scan without the flag returns rc 1 with empty stderr, the
# clean-tree face byte for byte. So a scan that silently lost `--untracked` reds
# here and nowhere else.
#
# THE LITERAL IS NOT A RETIRED REVIEWER NAME, deliberately, and the reason is the
# tree this validator runs in rather than taste. Sibling waves write this same
# working tree while this bar runs, so a plant carrying a banned name would be a
# real dead name on disk for as long as the plant exists, and a concurrent run of
# THIS check would red on it truthfully. A literal that ships nowhere proves the
# same two things, that the scan reaches an untracked file and that the ban
# machinery reddens on a hit, and it is invisible to every other check: it is not
# markdown, so [57] and [80] never see it; it holds no slash command, so [86]
# leaves it alone; and it lives at the repository root, which [55] does not cover.
#
# rrn_absent IS THE CALLER, NOT rrn_absent_all, AND THAT IS THE SECOND THING THIS
# CONTROL BUYS. rrn_absent had no caller at all: the live path runs
# rrn_absent_all, and the shared rename_absent_all re-enters rename_absent
# directly rather than through this fragment's wrapper, so the wrapper was dead
# text that looked like code. Its twin in [40] survives because
# scripts/test_ban_tokens.d/15-wi-absent-cases.sh sed-lifts it by name; nothing
# lifts this one. Calling it here is what makes it live, and it also reaches a
# branch nothing else in this repository reaches: rename_absent's
# `[ "${#RN_MODES[@]}" -gt 1 ]` test in 00-helpers.sh decides whether a
# verdict names the mode that found the hit, and every other caller of it is the
# two-mode [40] profile, so the FALSE side of that test, the one-mode wording,
# ran nowhere. The assertion below reads it directly.
#
# A CONTROL MUST NOT MOVE FAILED, on the rule [83], [87] and [88] all state at
# their own: the counter is read, the judge is called with its printing captured,
# and the counter is put back whatever happened. The DELTA is published rather
# than a yes/no because this control owes exactly one red and a bare "something
# moved" would accept the wrong one.
RRN_CTL_LIT='zzq-89-control-literal-that-ships-nowhere'
RRN_CTL_FILE=".hackify-89-control-$$"
RRN_CTL_DELTA=0
rrn_control_delta() {
  local before="$FAILED"
  rrn_absent "$RRN_CTL_LIT" > "$1" 2>&1
  RRN_CTL_DELTA=$((FAILED - before))
  FAILED="$before"
}

# THE CAPTURE FILE IS CHECKED, for the reason rename_absent checks its own: a
# failed mktemp leaves the redirection target empty, the redirection dies in the
# shell before rrn_absent runs, and the delta comes back 0 wearing the exact face
# of a scan that found nothing. THE PLANT IS REFUSED IF IT IS ALREADY THERE,
# rather than overwritten, because a file of that name means an earlier run died
# between writing it and removing it and a silent overwrite would hide that.
RRN_CTL_OUT=$(mktemp 2> /dev/null) || RRN_CTL_OUT=''
if [ -z "$RRN_CTL_OUT" ]; then
  red "  FAIL [89] the positive control could not create its capture file, so the ban scan below was never measured against a known hit and its silence is not a verdict"
  FAILED=$((FAILED + 1))
elif [ -e "$RRN_CTL_FILE" ]; then
  rm -f "$RRN_CTL_OUT"
  red "  FAIL [89] $RRN_CTL_FILE already exists, so an earlier run died mid-control; remove it by hand rather than letting this overwrite it"
  FAILED=$((FAILED + 1))
else
  printf '%s\n' "$RRN_CTL_LIT" > "$RRN_CTL_FILE"
  rrn_control_delta "$RRN_CTL_OUT"
  rm -f "$RRN_CTL_FILE"
  rrn_ctl_bad=0
  if [ "$RRN_CTL_DELTA" -ne 1 ]; then
    red "  FAIL [89] positive control, a literal planted in an untracked file at the repository root raised $RRN_CTL_DELTA red(s) rather than the 1 it owes; this scan cannot return a dirty result, so every 'survives in no live file' line above was printed by a scan that finds nothing"
    rrn_ctl_bad=1
  elif ! grep -qF -- "$RRN_CTL_FILE" "$RRN_CTL_OUT"; then
    red "  FAIL [89] positive control, the scan reddened but did not name $RRN_CTL_FILE, so it reddened for some reason other than the planted hit and proves nothing about the ban scan"
    rrn_ctl_bad=1
  elif grep -qF 'found by the' "$RRN_CTL_OUT"; then
    red "  FAIL [89] positive control, the verdict attributed the hit to a named scan mode, but this profile declares exactly one mode and that word exists to say which half of a union spoke; a mode word here means RN_MODES has grown a second entry that nothing in this fragment asked for"
    rrn_ctl_bad=1
  fi
  if [ "$rrn_ctl_bad" -eq 0 ]; then
    green "  ok   [89] positive control, a literal planted in an untracked file at the repository root raised the 1 red it owes, named the file it was found in, and named no scan mode, which is the one-mode wording this profile is the only caller of"
  else
    FAILED=$((FAILED + 1))
  fi
  rm -f "$RRN_CTL_OUT"
fi

# THE SCOPE ITSELF IS FLOORED, for the reason [40]'s WI_SCOPE_FLOOR states and
# measures: `git grep -qF -e <anything> -- ':(top)' ':(top,exclude)*'` returns rc 1
# with empty stderr, this block's clean-tree face exactly, so a scope that
# resolved to no file would clear all six names green having read nothing. The
# enumeration matches the SCAN's set rather than the tracked set, --others
# --exclude-standard included, because `--untracked` above reads both and a floor
# over the narrower set would not notice the wider one collapsing. Status is git
# ls-files' alone, no pipe inside the substitution for pipefail to launder and rc
# read next; no stderr capture, because git ls-files has no ambiguous rc 1 to
# break a tie on and its own message is left to print. A floor and not an exact
# count, at roughly half of the 281 files the scope measured when it was written,
# since live files come and go.
RRN_SCOPE_FLOOR=140
rrn_scope_out=$(git ls-files --cached --others --exclude-standard -- "${RRN_LIVE_PATHS[@]}")
rrn_scope_rc=$?
rrn_scope_n=0
while IFS= read -r rrn_scope_f; do
  [ -n "$rrn_scope_f" ] || continue
  rrn_scope_n=$((rrn_scope_n + 1))
done <<RRN_SCOPE_EOF
$rrn_scope_out
RRN_SCOPE_EOF
if [ "$rrn_scope_rc" -ne 0 ] || [ "$rrn_scope_n" -lt "$RRN_SCOPE_FLOOR" ]; then
  red "  FAIL [89] RRN_LIVE_PATHS resolved to $rrn_scope_n live file(s) at rc $rrn_scope_rc, against a floor of $RRN_SCOPE_FLOOR; the scope collapsed rather than the tree shrinking, so the ban scan below would have cleared all ${#RRN_DEAD[@]} names against no file at all"
  FAILED=$((FAILED + 1))
else
  green "  ok   the [89] scan scope resolves to $rrn_scope_n live file(s), at or above its floor of $RRN_SCOPE_FLOOR"
  rrn_absent_all "${RRN_DEAD[@]}"
fi
